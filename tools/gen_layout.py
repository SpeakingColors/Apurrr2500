#!/usr/bin/env python3
"""Generate src/editor/Layout.h from docs/mockup/layout.json (made by tools/dump_layout.py from the mockup page).
The native editor takes every position, size, label, font and tooltip from the mockup this way. Run from the repo root."""
import json
d = json.load(open('docs/mockup/layout.json'))
# The mockup has a preview rig under the controls ("not part of the plugin"). The real window leaves it out: the
# footer moves up so it sits right under the controls.
H = 616
FOOT_Y = 590.0
dy = FOOT_Y - d['foot'][1]
def q(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
def f(v):
    t = '%g' % v
    if 'e' in t: t = '%.4f' % v
    return t + ('' if '.' in t else '.0') + 'f'
def rc(r): return '{ ' + ', '.join(f(v) for v in r) + ' }'
def sh(r, dy): return [r[0], r[1] + dy, r[2], r[3]]
def tx(t, dy=0):
    return '{ %s, %s, %s, %s, %d, %s, %s, %s, %d }' % (q(t['t']), rc(sh(t['r'], dy)), f(t['fs']), 'true' if t['mono'] else 'false', t['fw'],
                                                      'true' if t['it'] else 'false', f(t['ls']), 'true' if t['up'] else 'false', t['col'])
colidx = {'#02ebba': 0, '#ffd100': 1, '#f57f01': 2, '#ff1383': 3, '#6cc9f5': 4, '#a43dff': 5}
def bcol(s):
    import re
    m = re.findall(r'\d+', s); v = '#%02x%02x%02x' % tuple(int(x) for x in m[:3]); return colidx.get(v, 0)
ids = {'Threshold': 'thr', 'Ratio': 'ratio', 'Make-up': 'gain', 'Link': 'link', 'Attack': 'attack', 'Release': 'release', 'Var': 'relVar', 'Mix': 'mix'}
o = []
o.append('// GENERATED by tools/gen_layout.py from docs/mockup/layout.json. Do not edit by hand.')
o.append('#pragma once')
o.append('namespace layout {')
o.append('struct Rc { float x, y, w, h; };')
o.append('// col: -1 ink, -2 dim, -3 title, -4 accent, otherwise 0xRRGGBB')
o.append('struct Txt { const char* s; Rc r; float fs; bool mono; int fw; bool italic; float ls; bool up; int col; };')
o.append('struct Btn { Rc r; const char* tip; const char* t; float fs; int fw; };')
o.append('struct Cv { Rc r; const char* tip; int w, h; };')
o.append('struct Chip { Rc r; const char* t; const char* tip; };')
o.append('struct Seg { Rc r; const char* t; const char* tip; int lc; Rc tr; Rc dot; float fs; };')
o.append('struct Knob { const char* id; const char* name; Txt label; Rc knob; Rc val; const char* tip; int col; };')
o.append('constexpr int W = 1360, H = %d;' % H)
for k in ['cheekL', 'cheekR', 'hdr', 'disp', 'ctl', 'logo']:
    r = list(d[k])
    if k.startswith('cheek'): r[3] = H
    o.append('constexpr Rc %s = %s;' % (k, rc(r)))
o.append('constexpr Rc body = %s;' % rc([d['body'][0], d['body'][1], d['body'][2], H - 46 - 26]))
o.append('constexpr Rc meters = %s;' % rc([d['meters'][0], d['meters'][1], d['meters'][2], H - 46 - 26]))
o.append('constexpr Rc foot = %s;' % rc([d['foot'][0], FOOT_Y, d['foot'][2], d['foot'][3]]))
o.append('constexpr Txt nameA = %s;' % tx(d['nameA']))
o.append('constexpr Txt nameB = %s;' % tx(d['nameB']))
o.append('constexpr Txt s87 = %s;' % tx(d['s87']))
o.append('constexpr Txt footL = %s;' % tx(d['footL'], dy))
o.append('constexpr Txt winsz = %s;' % tx(d['winsz'], dy))
for k, t in d['hbtn'].items():
    o.append('constexpr Btn %s = { %s, %s, %s, %s, %d };' % (k, rc(t['r']), q(t['tip']), q(t['t']), f(t['fs']), t['fw']))
for k, t in d['cv'].items():
    r = list(t['r'])
    o.append('constexpr Cv %s = { %s, %s, %d, %d };' % (k, rc(r), q(t['tip']), t['w'], t['h']))
o.append('constexpr Txt caps[%d] = { %s };' % (len(d['caps']), ', '.join(tx(c) for c in d['caps'])))
o.append('constexpr Rc shRect[4] = { %s };' % ', '.join(rc(s['r']) for s in d['sh']))
o.append('constexpr int shCol[4] = { %s };' % ', '.join(str(bcol(s['bcol'])) for s in d['sh']))
o.append('constexpr Txt shText[8] = { %s };' % ', '.join(tx(t) for s in d['sh'] for t in s['texts']))
o.append('constexpr Knob knobs[%d] = {\n    %s };' % (len(d['kc']), ',\n    '.join('{ %s, %s, %s, %s, %s, %s, %d }' % (q(ids[k['aria']]), q(k['aria']), tx(k['label']), rc(k['knob']), rc(k['val']), q(k['tip']), colidx.get(k['kcol'].lower(), 0)) for k in d['kc'])))
for nm, strip in zip(['chipRatio', 'chipLink', 'chipAttack', 'chipRelease'], d['strips']):
    o.append('constexpr Chip %s[%d] = { %s };' % (nm, len(strip), ', '.join('{ %s, %s, %s }' % (rc(c['r']), q(c['t']), q(c['tip'])) for c in strip)))
for nm, sg in zip(['Knee', 'Make', 'Tilt', 'Type', 'Shape', 'Blend', 'Meter'], d['segs']):
    o.append('constexpr Seg seg%s[%d] = { %s };' % (nm, len(sg['btns']), ', '.join('{ %s, %s, %s, %d, %s, %s, %s }' % (rc(b['r']), q(b['t']), q(b['tip']), b['lc'], rc(b['tr']), rc(b['dot']), f(b['fs'])) for b in sg['btns'])))
o.append('constexpr Txt segLabel[7] = { %s };' % ', '.join(tx(s['label']) for s in d['segs']))
for nm, t in zip(['tglExt', 'tglIn', 'tglMatch'], d['tgls']):
    o.append('constexpr Seg %s = { %s, %s, %s, %d, %s, %s, %s };' % (nm, rc(t['r']), q(t['t']), q(t['tip']), t['lc'], rc(t['tr']), rc(t['dot']), f(t['fs'])))
o.append('constexpr Rc ledThr = %s;' % rc(d['led']['r']))
o.append('constexpr const char* ledThrTip = %s;' % q(d['led']['tip']))
o.append('constexpr Rc plate = %s;' % rc(d['plate']['r']))
o.append('constexpr const char* plateTip = %s;' % q(d['plate']['tip']))
o.append('constexpr Txt plateText[3] = { %s };' % ', '.join(tx(t) for t in d['plate']['texts']))
o.append('constexpr Rc plateSvg = %s;' % rc(d['plate']['svg']))
o.append('constexpr Txt meterCap[3] = { %s };' % ', '.join(tx(t) for t in d['mcap']))
o.append('constexpr Rc pkRect[3] = { %s };' % ', '.join(rc(t['r']) for t in d['pk']))
o.append('constexpr Txt pkText = %s;' % tx(d['pk'][0]))
o.append('} // namespace layout')
open('src/editor/Layout.h', 'w').write('\n'.join(o) + '\n')
print('ok', len(o), 'lines')
